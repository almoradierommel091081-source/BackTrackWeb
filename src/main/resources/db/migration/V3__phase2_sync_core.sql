-- ============================================================================
-- V3 - Phase 2: synchronization core.
--
-- Additive only: five new tables plus one new column on sales and one on
-- business_settings. No existing table is rebuilt, no column is dropped and no
-- row is rewritten.
--
-- Contents:
--   1. sync_devices          - one row per Windows/Android installation
--   2. sync_operations       - the idempotency ledger (op_id is the key)
--   3. sync_leases           - single-writer lease + fencing epoch per business
--   4. sync_number_leases    - server issued receipt-number blocks per device
--   5. sync_change_log       - ordered change feed used by pull
--   6. inventory_discrepancies - accept-and-flag record for short stock
--   7. two additive columns  - sales.stock_conflict, business_settings.business_id
-- ============================================================================

-- 0. Businesses get an identity column --------------------------------------
-- Phase 1 inserted the single business with an explicit id. A server that hosts
-- several businesses needs the database to assign ids; the existing row keeps
-- id 1 and the sequence continues after it.
alter table businesses alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('businesses', 'id'),
              (select coalesce(max(id), 1) from businesses));

-- 1. Devices ---------------------------------------------------------------
create table sync_devices (
    id bigserial primary key,
    uuid varchar(36) not null,
    business_id bigint not null references businesses (id),
    name varchar(120) not null,
    platform varchar(20) not null,
    user_id bigint not null references users (id),
    -- Only the SHA-256 of the token is ever stored.
    token_hash varchar(64) not null,
    token_prefix varchar(12) not null,
    token_expires_at timestamp(6) with time zone not null,
    lease_epoch bigint not null default 0,
    last_seen_at timestamp(6) with time zone,
    revoked_at timestamp(6) with time zone,
    revoked_reason varchar(255),
    created_at timestamp(6) with time zone not null default now()
);

create unique index ux_sync_devices_uuid on sync_devices (uuid);
create unique index ux_sync_devices_token_hash on sync_devices (token_hash);
create index ix_sync_devices_business on sync_devices (business_id);
create index ix_sync_devices_user on sync_devices (user_id);

-- 2. Idempotency ledger ----------------------------------------------------
create table sync_operations (
    op_id varchar(64) not null primary key,
    business_id bigint not null references businesses (id),
    device_id bigint references sync_devices (id),
    op_type varchar(40) not null,
    aggregate_uuid varchar(36),
    applied_at timestamp(6) with time zone not null default now(),
    server_seq bigint not null,
    result_json text not null
);

create index ix_sync_operations_business_seq on sync_operations (business_id, server_seq);

-- 3. Single-writer lease ---------------------------------------------------
create table sync_leases (
    business_id bigint not null primary key references businesses (id),
    active_device_id bigint references sync_devices (id),
    epoch bigint not null default 0,
    updated_at timestamp(6) with time zone not null default now(),
    updated_by bigint references users (id)
);

-- Every business starts with no active device and epoch zero.
insert into sync_leases (business_id, active_device_id, epoch, updated_at)
select id, null, 0, now() from businesses;

-- 4. Receipt number blocks -------------------------------------------------
create table sync_number_leases (
    id bigserial primary key,
    business_id bigint not null references businesses (id),
    device_id bigint not null references sync_devices (id),
    prefix varchar(12) not null,
    first_value bigint not null,
    last_value bigint not null,
    issued_at timestamp(6) with time zone not null default now(),
    expires_at timestamp(6) with time zone not null,
    constraint ux_sync_number_leases_prefix unique (business_id, prefix, first_value)
);

create index ix_sync_number_leases_device on sync_number_leases (device_id);
create index ix_sync_number_leases_business on sync_number_leases (business_id);

-- 5. Change feed for pull --------------------------------------------------
create table sync_change_log (
    id bigserial primary key,
    business_id bigint not null references businesses (id),
    entity_type varchar(30) not null,
    entity_uuid varchar(36) not null,
    operation varchar(10) not null,
    server_seq bigint not null,
    changed_at timestamp(6) with time zone not null default now()
);

create unique index ux_sync_change_log_business_seq on sync_change_log (business_id, server_seq);
create index ix_sync_change_log_entity on sync_change_log (business_id, entity_type, entity_uuid);

-- 6. Inventory discrepancies ----------------------------------------------
create table inventory_discrepancies (
    id bigserial primary key,
    business_id bigint not null references businesses (id),
    product_id bigint not null references products (id),
    sale_uuid varchar(36),
    movement_uuid varchar(36),
    expected_stock integer not null,
    resulting_stock integer not null,
    delta integer not null,
    status varchar(20) not null default 'OPEN',
    note varchar(255),
    created_at timestamp(6) with time zone not null default now(),
    resolved_at timestamp(6) with time zone,
    resolved_by bigint references users (id)
);

create index ix_inventory_discrepancies_business_status on inventory_discrepancies (business_id, status);
create index ix_inventory_discrepancies_product on inventory_discrepancies (product_id);

-- 7. Additive columns ------------------------------------------------------
alter table sales add column stock_conflict boolean not null default false;
create index ix_sales_stock_conflict on sales (business_id, stock_conflict);

alter table business_settings add column business_id bigint not null default 1 references businesses (id);
create unique index ux_business_settings_business on business_settings (business_id);

-- Settings are now a syncable record like every other business table, with
-- the same uuid identity and version used to detect conflicting edits.
alter table business_settings add column uuid varchar(36);
alter table business_settings add column version bigint not null default 0;
update business_settings set uuid = gen_random_uuid()::text where uuid is null;
alter table business_settings alter column uuid set not null;
create unique index ux_business_settings_uuid on business_settings (uuid);

-- 8. Document counters are now per business ---------------------------------
-- The existing counter is renamed, not reset: its next value is preserved, so
-- receipt numbers continue exactly where they were.
update number_sequences set name = 'sale-1' where name = 'sale';

-- 9. Handover history -------------------------------------------------------
-- Every claim, release, handover and forced handover is recorded here, so the
-- transfer of control over a business is auditable after the fact.
create table sync_lease_events (
    id bigserial primary key,
    business_id bigint not null references businesses (id),
    epoch bigint not null,
    event varchar(30) not null,
    device_id bigint references sync_devices (id),
    previous_device_id bigint references sync_devices (id),
    actor_user_id bigint references users (id),
    note varchar(500),
    created_at timestamp(6) with time zone not null default now()
);

create index ix_sync_lease_events_business on sync_lease_events (business_id, created_at desc);

-- 10. Uniqueness becomes per business ---------------------------------------
-- Two businesses may now use the same SKU, category name or receipt number.
-- Each stays unique inside its own business. Only the constraints change; no
-- row is touched and no data is lost.
--
-- The old constraints are found by what they cover, not by name. A database
-- built by the migration history has them called uk_products_sku and so on,
-- while the live BackTrack database was created by Hibernate, which names a
-- unique constraint ukfhmd06dsmj6k0n90swsh8ie9g. Dropping by name would work
-- on a fresh install and fail on the real server, so the names are looked up.
do $$
declare
    target record;
    con record;
    idx record;
begin
    for target in
        select * from (values ('products', 'sku'),
                              ('product_categories', 'name'),
                              ('sales', 'sale_number')) as t(tbl, col)
    loop
        -- A unique constraint covering exactly this one column.
        for con in
            select c.conname
            from pg_constraint c
            join pg_class rel on rel.oid = c.conrelid
            join pg_namespace ns on ns.oid = rel.relnamespace
            where ns.nspname = current_schema()
              and rel.relname = target.tbl
              and c.contype = 'u'
              and (select array_agg(a.attname::text order by a.attname)
                   from unnest(c.conkey) as cols(attnum)
                   join pg_attribute a
                     on a.attrelid = c.conrelid and a.attnum = cols.attnum)
                  = array[target.col]
        loop
            execute format('alter table %I drop constraint %I', target.tbl, con.conname);
        end loop;

        -- The same thing expressed as a bare unique index (no constraint).
        for idx in
            select ic.relname
            from pg_index i
            join pg_class ic on ic.oid = i.indexrelid
            join pg_class rel on rel.oid = i.indrelid
            join pg_namespace ns on ns.oid = rel.relnamespace
            where ns.nspname = current_schema()
              and rel.relname = target.tbl
              and i.indisunique
              and not i.indisprimary
              and not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
              and i.indnkeyatts = 1
              and (select a.attname from pg_attribute a
                   where a.attrelid = i.indrelid and a.attnum = i.indkey[0]) = target.col
        loop
            execute format('drop index %I', idx.relname);
        end loop;
    end loop;
end $$;

create unique index ux_products_business_sku on products (business_id, sku);
create unique index ux_product_categories_business_name on product_categories (business_id, name);
create unique index ux_sales_business_sale_number on sales (business_id, sale_number);
